#!/usr/bin/env node
// Builds switch/d2c-team.template.yaml from contracts/roster.json and switch/agents/<id>.md, so they can't drift.
//   node scripts/build-template.mjs           # write the template
//   node scripts/build-template.mjs --check   # exit 1 if the template is stale or an .md lost the Telegram rules
// Team = roster agents except the librarian. Instructions = the .md body minus its "# <id>" heading
// (exactly what scripts/switch-sync-agents.sh pushes to the live agents).
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url);
const read = (p) => readFileSync(new URL(p, root), 'utf8');
const roster = JSON.parse(read('contracts/roster.json'));
const style = read('switch/TELEGRAM_STYLE.md').trim();
const team = roster.people.filter((p) => p.kind === 'agent' && p.id !== 'librarian');
const problems = [];
const MODEL = 'claude-haiku-5-5'; // team model (cost); keep in sync with scripts/switch-*.sh and server/src/switch.ts TEAM_MODEL

const agents = team.map((p) => {
  const body = read(`switch/agents/${p.id}.md`).split('\n').slice(1).join('\n').trim();
  if (!body.includes(style)) problems.push(`switch/agents/${p.id}.md: TELEGRAM_STYLE.md block missing or edited`);
  return [
    `  - name: "${p.id}"`,
    `    description: ${JSON.stringify(p.role)}`,
    '    addressing: anyone',
    '    provider: "{provider}"',
    `    model: "${MODEL}"`,
    '    location: "{location}"',
    '    directory: "{directory}"',
    '    join: ["{team_room}"]',
    '    instructions: |',
    ...body.split('\n').map((l) => (l ? `      ${l}` : '')),
  ].join('\n');
});

const yaml = `# D2C Agent HQ team: ${team.length} agents for Kesar & Co. (schema: Switch docs/TEMPLATES.md, version 1).
# GENERATED by scripts/build-template.mjs from contracts/roster.json + switch/agents/*.md. Do not edit by hand.
#
# One Telegram forum group, "Kratos D2C", is the single Switch room; each department is a
# forum topic inside it (Switch maps a topic to a thread). Telegram bots can't create chats,
# so the group must exist with @kratosd2c_bot in it before this runs; every agent \`join\`s it.
# See docs/GO_LIVE.md and scripts/switch-up.sh.
version: 1

params:
  provider:
    type: provider
    description: Coding agent that runs every teammate.
    default: [claude, codex, opencode]
    input: advanced
  location:
    type: location
    default: local
    input: advanced
  directory:
    type: directory
    description: The D2C Agent HQ repo checkout. All agents share it to read data/ and write gallery/.
    default: /Users/snehal/Desktop/repos/switch-wmd
  team_room:
    type: room
    label: "Team group (Telegram forum)"
    default: ["${roster.telegram.group}"]
    input: advanced

form:
  advanced:
    label: Provider, machine and room
    open: false

agents:
${agents.join('\n')}
`;

const out = new URL('switch/d2c-team.template.yaml', root);
if (process.argv.includes('--check')) {
  if (readFileSync(out, 'utf8') !== yaml) problems.push('switch/d2c-team.template.yaml is stale: run node scripts/build-template.mjs');
  if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
  console.log(`template up to date: ${team.length} agents`);
} else {
  if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
  writeFileSync(out, yaml);
  console.log(`wrote switch/d2c-team.template.yaml: ${team.length} agents`);
}
